"""LLM-generated 'insurance fraud news' briefing for the dashboard news panel.

The items are generated by the app's Claude endpoint on first request and cached
in-process (there is no external news API / internet egress in the app runtime).
They are illustrative, professional demo content — not real, dated articles.
"""
from __future__ import annotations

import json
import re

from server.db import llm

# Simple process-wide cache so we don't call the LLM on every page load.
_CACHE: dict | None = None

_SYSTEM = (
    "You are a fraud-intelligence editor for an insurance analytics platform. "
    "Produce concise, realistic, professional news-style briefing items about fraud in the "
    "insurance sector (claims fraud, application fraud, organised rings, digital/identity fraud, "
    "regulation, detection technology, notable enforcement actions). "
    "Write in clear British English suitable for a claims-intelligence audience. "
    "These are illustrative briefing items for a demo dashboard, NOT real press articles: do NOT "
    "invent specific company names, real people, exact monetary figures presented as fact, or "
    "precise dates. Keep it thematic and plausible. Return STRICT JSON only."
)

_USER = (
    "Generate 6 insurance-fraud briefing items. Return a JSON object with a single key "
    '"items" whose value is an array of 6 objects, each with exactly these fields:\n'
    '  "category": one of "Claims Fraud", "Digital & Identity", "Organised Rings", '
    '"Regulation", "Detection Tech", "Market Trend"\n'
    '  "headline": a punchy 6-12 word headline (string)\n'
    '  "summary": 1-2 sentences (max ~40 words) explaining the item and why it matters (string)\n'
    '  "impact": one of "High", "Medium", "Low" — relevance to fraud teams\n'
    "Vary the categories across the 6 items. Return ONLY the JSON object, no prose, no code fences."
)

