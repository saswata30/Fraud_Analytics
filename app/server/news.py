def _coerce(raw: str) -> dict:
    """Parse the LLM output into {items:[...]} defensively."""
    txt = (raw or "").strip()
    # strip code fences if present
    txt = re.sub(r"^```(?:json)?\s*|\s*```$", "", txt, flags=re.IGNORECASE).strip()
    # grab the outermost JSON object
    m = re.search(r"\{.*\}", txt, flags=re.DOTALL)
    if m:
        txt = m.group(0)
    data = json.loads(txt)
    items = data.get("items") if isinstance(data, dict) else data
    if not isinstance(items, list) or not items:
        raise ValueError("no items")
    clean = []
    allowed_impact = {"High", "Medium", "Low"}
    for it in items[:8]:
        if not isinstance(it, dict):
            continue
        clean.append({
            "category": str(it.get("category") or "Market Trend")[:40],
            "headline": str(it.get("headline") or "").strip()[:160],
            "summary": str(it.get("summary") or "").strip()[:400],
            "impact": it.get("impact") if it.get("impact") in allowed_impact else "Medium",
        })
    clean = [c for c in clean if c["headline"]]
    if not clean:
        raise ValueError("no valid items")
    return {"items": clean}


def news(refresh: bool = False) -> dict:
    """Return the fraud-news briefing (LLM-generated, cached in-process)."""
    global _CACHE
    if _CACHE is not None and not refresh:
        return _CACHE
    try:
        raw = llm(_SYSTEM, _USER, temperature=0.6, max_tokens=1200)
        result = _coerce(raw)
        result["source"] = "ai"
    except Exception:
        result = dict(_FALLBACK)
        result["source"] = "fallback"
    _CACHE = result
    return result
